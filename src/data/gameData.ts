// ==================== HVĚZDIČKOVÝ SYSTÉM JAKOSTI KARET (Hnát) ====================
// Každá karta v brašně nebo nabídce může nést 0 až 5 hvězdiček jakosti (stars: 0–5).
// Každá hvězdička přidává +10 % k číselným účinkům karty (Zranění, Blok, úleva od Únavy, Sůl na kůži).
// Náklady na Akce (cost) i nápřah (pre v Aug) zůstávají neměnné.

export const MAX_CARD_STARS = 5;

export function starValueMult(stars: number = 0): number {
  const capped = Math.min(MAX_CARD_STARS, Math.max(0, stars || 0));
  return 1 + capped * 0.1; // 1★ = +10 %, 2★ = +20 %, 3★ = +30 %, 4★ = +40 %, 5★ = +50 %
}

export function starPriceMult(stars: number = 0): number {
  const capped = Math.min(MAX_CARD_STARS, Math.max(0, stars || 0));
  return 1 + capped * 0.15; // 1★ = +15 %, 2★ = +30 %, 3★ = +45 %, 4★ = +60 %, 5★ = +75 % ceny v šenku
}

export function starEmoji(stars?: number): string {
  if (!stars || stars <= 0) return "";
  const full = Math.floor(stars);
  const half = stars - full >= 0.5 ? 1 : 0;
  return "★".repeat(full) + (half ? "½" : "");
}

export function getCardUpgradeCost(currentStars: number = 0): number {
  // Progresivní cena vylepšení: 6 krejcarů za 1. hvězdičku, +2 za každou další
  return 6 + Math.max(0, currentStars) * 2;
}

export function rollShopCardStars(rand?: () => number): number {
  const r = (rand || Math.random)();
  // 60 % bez hvězdičky (0★), 24 % (1★), 11 % (2★), 5 % (3★)
  if (r < 0.6) return 0;
  if (r < 0.84) return 1;
  if (r < 0.95) return 2;
  return 3;
}

